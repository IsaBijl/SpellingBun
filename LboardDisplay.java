    private static DefaultListModel<String> arrayToDLM(int[][] array, boolean nameList) {
        DefaultListModel<String> output = new DefaultListModel<>();
        
        if (nameList) {
            for (int entryIndex = 0; entryIndex < Leaderboard.LIST_LENGTH; entryIndex++) {
                String currentName = "";
                for (int charIndex = 0; charIndex < Leaderboard.NAME_LENGTH; charIndex++) {
                    currentName += (char) array[entryIndex][charIndex];
                }
                output.add(entryIndex, currentName);
            }
        } else {
            for (int entryIndex = 0; entryIndex < Leaderboard.LIST_LENGTH; entryIndex++) {
                int currentScore = array[entryIndex][Leaderboard.NAME_LENGTH];
                output.add(entryIndex, String.format("%06d", currentScore));
            }
        }
        
        return output;
    }

