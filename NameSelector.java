public void changeChar(boolean up) {
        char current = charArray[activeIndex].charAt(0);
        if (current == 'A' && up) {
            charArray[activeIndex] = "Z";
        } else if (current == 'Z' && !up) {
            charArray[activeIndex] = "A";
        } else {
            char newChar;
            if (up) {
                newChar = (char) ((int) current - 1);
            } else {
                newChar = (char) ((int) current + 1);
            }
            charArray[activeIndex] = Character.toString(newChar);
        }
    }
    
    public void changeActive(boolean right) {
        if (activeIndex == 2 && right) { // change index
            activeIndex = 0;
        } else if (activeIndex == 0 && !right) {
            activeIndex = 2;
        } else {
            if (right) {
                activeIndex += 1;
            } else {
                activeIndex += -1;
            }
        }
    }
    
    public void visualUpdate() {
        this.upZero.setEnabled(activeIndex == 0);
        this.downZero.setEnabled(activeIndex == 0);
        this.upOne.setEnabled(activeIndex == 1);
        this.downOne.setEnabled(activeIndex == 1);
        this.upTwo.setEnabled(activeIndex == 2);
        this.downTwo.setEnabled(activeIndex == 2);
        
        this.charOne.setText(charArray[0]);
        this.charTwo.setText(charArray[1]);
        this.charThree.setText(charArray[2]);
    }
    
